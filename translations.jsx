function detectLanguage() {
  const nav = ((typeof navigator !== 'undefined' && navigator.language) || 'hu').toLowerCase();
  if (nav.startsWith('en')) return 'en';
  if (nav.startsWith('it')) return 'it';
  return 'hu';
}

function makeTranslator(lang) {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.hu;
  return function t(key, params) {
    let str = dict[key] !== undefined ? dict[key] : (TRANSLATIONS.hu[key] !== undefined ? TRANSLATIONS.hu[key] : key);
    if (params) {
      Object.keys(params).forEach((k) => {
        str = str.split('{' + k + '}').join(params[k]);
      });
    }
    return str;
  };
}
